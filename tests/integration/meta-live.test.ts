// Live evaluation on test-data/real (read-only). Skipped unless VALENCE_LIVE=1.
// Real MusicBrainz requests (1 req / 1.1 s, cached in .sandbox/mb-cache); writes tests/fixtures/meta/real-sample-report.md.

import { describe, expect, it } from 'vitest'
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, resolve, sep } from 'node:path'
import { createMetadataService, fileCache, inferLooseCluster, sanitizeTags, type IdentifyResult } from '@main/metadata'
import { albumSim, strSim, titleSim } from '@main/metadata/util'
import { probeFile } from '@main/tags/read'
import type { TrackTags } from '@shared/types'

const ROOT = resolve('test-data/real')
const LIVE = process.env.VALENCE_LIVE === '1' && existsSync(ROOT)

interface Sample { relPath: string; tags: TrackTags; durationMs: number }

function walk(dir: string, out: string[] = []): string[] {
  for (const n of readdirSync(dir).sort()) {
    const p = join(dir, n)
    if (statSync(p).isDirectory()) walk(p, out)
    else if (/\.(mp3|flac|m4a|ogg|opus)$/i.test(n)) out.push(p)
  }
  return out
}

const pct = (n: number, d: number) => (d ? `${Math.round((100 * n) / d)}%` : 'n/a')
const cell = (s: unknown) => String(s ?? '').replace(/\|/g, '\\|').slice(0, 60)

describe.skipIf(!LIVE)('real-sample evaluation (live)', () => {
  it('heuristics and identification on test-data/real', { timeout: 1_800_000 }, async () => {
    const samples: Sample[] = []
    for (const f of walk(ROOT)) {
      const p = await probeFile(f, { covers: false, duration: true })
      samples.push({ relPath: relative(ROOT, f).split(sep).join('/'), tags: p.tags, durationMs: p.format.durationMs })
    }
    const lines: string[] = ['# Real-sample metadata report', '', `Generated by \`tests/integration/meta-live.test.ts\` (VALENCE_LIVE=1) over ${samples.length} files in test-data/real. MusicBrainz only (no AcoustID key).`, '']

    // ---- heuristics: files stripped of all tags, inferred from paths/filenames alone ----
    const stripped = inferLooseCluster(samples.map((s) => ({ ...s, tags: {} })))
    const truth = samples.map((s) => sanitizeTags(s.tags))
    const fields = ['title', 'artist', 'album', 'albumartist', 'tracknumber'] as const
    const agree = (k: (typeof fields)[number], a: unknown, b: unknown) =>
      k === 'tracknumber' ? a === b : typeof a === 'string' && typeof b === 'string' && (k === 'album' ? albumSim(a, b) : k === 'title' ? titleSim(a, b) : strSim(a, b)) >= 0.9
    lines.push('## Loose-file heuristics (tags removed, inferred from folder + filename)', '', '| field | files with tag | inferred | agrees with tag |', '|---|---|---|---|')
    for (const k of fields) {
      const idx = truth.map((t, i) => (t[k] !== undefined ? i : -1)).filter((i) => i >= 0)
      const inferred = idx.filter((i) => stripped[i][k] !== undefined)
      const ok = inferred.filter((i) => agree(k, stripped[i][k], truth[i][k]))
      lines.push(`| ${k} | ${idx.length} | ${pct(inferred.length, idx.length)} | ${pct(ok.length, idx.length)} (${pct(ok.length, inferred.length)} of inferred) |`)
    }
    const withTags = inferLooseCluster(samples)
    const changed = samples.filter((s, i) => (['title', 'artist', 'album'] as const).some((k) => s.tags[k] && withTags[i][k] !== s.tags[k])).length
    const filled = samples.filter((s, i) => (['title', 'artist', 'album', 'tracknumber'] as const).some((k) => s.tags[k] === undefined && withTags[i][k] !== undefined)).length
    lines.push('', `With the real tags: ${changed} files had title/artist/album cleaned (mojibake, junk, explicit markers), ${filled} files had a missing field filled from folder/filename.`, '')

    // ---- identification ----
    const svc = createMetadataService({ cache: fileCache(resolve('.sandbox/mb-cache')), contact: () => '', appVersion: '0.1', acoustidKey: () => null, fpcalcPath: () => null })
    const byDir = new Map<string, number[]>()
    samples.forEach((s, i) => {
      if (!s.relPath.startsWith('albums/')) return
      const d = s.relPath.split('/').slice(0, -1).join('/')
      byDir.set(d, [...(byDir.get(d) ?? []), i])
    })
    const albumDirs = [...byDir.keys()].filter((_, i) => i % 2 === 0)
    const loose = samples.map((s, i) => (s.relPath.startsWith('loose/') ? i : -1)).filter((i) => i >= 0).filter((_, j) => j % 4 === 0)

    type Row = { name: string; n: number; res: IdentifyResult; agrees: boolean; ms: number }
    const rows: Row[] = []
    const run = async (name: string, idx: number[]) => {
      const t0 = Date.now()
      const tracks = idx.map((i, k) => ({ index: k, relPath: samples[i].relPath, durationMs: samples[i].durationMs, tags: withTags[i] }))
      const res = await svc.identify({ source: 'import', albumTags: {}, tracks })
      const tagAlbum = withTags[idx[0]].album
      const agrees = !!res.release && (idx.length === 1 ? titleSim(res.trackTags[0]?.title, withTags[idx[0]].title) >= 0.85 : !!tagAlbum && albumSim(tagAlbum, res.release.title) >= 0.85)
      rows.push({ name, n: idx.length, res, agrees, ms: Date.now() - t0 })
    }
    for (const d of albumDirs) await run(d.replace(/^albums\//, ''), byDir.get(d)!)
    for (const i of loose) await run(samples[i].relPath, [i])

    const summary = (rs: Row[], label: string) => {
      const c = (s: string) => rs.filter((r) => r.res.status === s).length
      const autoOk = rs.filter((r) => r.res.status === 'auto' && r.agrees).length
      return `| ${label} | ${rs.length} | ${c('auto')} (${pct(c('auto'), rs.length)}) | ${c('review')} | ${c('unmatched')} | ${autoOk}/${c('auto')} |`
    }
    const albumsRows = rows.filter((r) => r.n > 1)
    const singleRows = rows.filter((r) => r.n === 1)
    lines.push('## Identification (tags as found + heuristics, no fingerprints)', '', '| set | items | auto | review | unmatched | auto agreeing with tag album/title |', '|---|---|---|---|---|---|')
    lines.push(summary(albumsRows, 'album folders'), summary(singleRows, 'loose singles'), '')
    lines.push('### Per item', '', '| item | files | status | score | release | type | date | matched tracks | agrees |', '|---|---|---|---|---|---|---|---|---|')
    for (const r of rows) {
      const matched = r.res.trackTags.filter(Boolean).length
      lines.push(`| ${cell(r.name)} | ${r.n} | ${r.res.status} | ${r.res.score.toFixed(2)} | ${cell(r.res.release ? `${r.res.release.title} — ${r.res.release.artist}` : '')} | ${cell(r.res.release?.type)} | ${cell(r.res.release?.date)} | ${matched}/${r.n} | ${r.res.release ? (r.agrees ? 'yes' : 'no') : ''} |`)
    }
    lines.push('', 'Notes: "agrees" compares the chosen release title with the album tag (albums) or the matched track title with the title tag (singles); a singleton matched to the original album rather than the tagged single/compilation is intentional and shows as a disagreement on album only, not here.', '')
    writeFileSync(resolve('tests/fixtures/meta/real-sample-report.md'), lines.join('\n'))
    expect(rows.length).toBeGreaterThan(10)
  })
})
