const num = (s) => Number(s)

function shapeToPath(tag, attrs) {
  const a = Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]))
  if (a.fill === 'none') return ''
  if (tag === 'path') return a.d
  if (tag === 'circle') {
    const [cx, cy, r] = [num(a.cx), num(a.cy), num(a.r)]
    return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`
  }
  if (tag === 'rect') {
    const [x, y, w, h] = [num(a.x ?? 0), num(a.y ?? 0), num(a.width), num(a.height)]
    return `M${x} ${y}h${w}v${h}h${-w}z`
  }
  if (tag === 'ellipse') {
    const [cx, cy, rx, ry] = [num(a.cx), num(a.cy), num(a.rx), num(a.ry)]
    return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0z`
  }
  if (tag === 'polygon') return `M${a.points.trim()}z`
  throw new Error(`Unhandled <${tag}>`)
}

const out = []
for (const [name, file] of Object.entries(MAP)) {
  const svg = readFileSync(join(root, `${file}.svg`), 'utf8')
  const d = [...svg.matchAll(/<(path|circle|rect|ellipse|polygon)\b([^>]*)\/?>/g)].map((m) => shapeToPath(m[1], m[2])).filter(Boolean).join('')
  if (!d) throw new Error(`No shapes in ${file}`)
  out.push(`  ${name}: '${d}',`)
}

